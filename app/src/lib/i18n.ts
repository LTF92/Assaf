export type Lang = 'ar' | 'en';
export const systemLang: Lang = getLocales()[0]?.languageCode === 'ar' ? 'ar' : 'en';

/** Current strings. Replaced in place by setLanguage, so `t.x` read while rendering is always current. */
export const t: typeof en = { ...(systemLang === 'ar' ? ar : en) };
/** True when the app language reads right to left. */
export let isRTL = systemLang === 'ar' || I18nManager.isRTL;
export let lang: Lang = systemLang;

export function setLanguage(choice: Lang | 'system') {
  lang = choice === 'system' ? systemLang : choice;
  Object.assign(t, lang === 'ar' ? ar : en);
  isRTL = lang === 'ar';
}
